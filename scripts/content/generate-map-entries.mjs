/* ---------------- 自动标签（有阈值，避免所有图都挂同一批标签） ---------------- */
/** 标签会变成 /tags/<tag>/ 路径：去掉文件系统与 URL 里的危险字符 */
const safeTag = (t) =>
  String(t || '')
    .replace(/[\\/:*?"<>|#%]/g, '·')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 24);

/* 标签大小写归一：
 * 同一个标签出现 Boss / boss / BOSS 三种写法时，Windows 上会写进同一个目录，
 * 但 Cloudflare 是大小写敏感的文件系统，另一种写法就会 404。
 * 这里先统计所有来源（富内容 JSON + 检索资料）的写法，按「富内容优先 → 出现次数多优先」
 * 选出一个规范写法，生成时统一使用。 */
const tagVariants = new Map(); // lower -> Map(写法 -> {count, curated})
const noteTag = (tag, curated) => {
  const t = safeTag(tag);
  if (!t) return;
  const key = t.toLowerCase();
  if (!tagVariants.has(key)) tagVariants.set(key, new Map());
  const variants = tagVariants.get(key);
  const cur = variants.get(t) || { count: 0, curated: false };
  cur.count++;
  if (curated) cur.curated = true;
  variants.set(t, cur);
};
const canonTag = (tag) => {
  const t = safeTag(tag);
  if (!t) return t;
  const variants = tagVariants.get(t.toLowerCase());
  if (!variants) return t;
  // 平票时优先选「不是全大写前缀」的写法（Boss战 优于 BOSS战）
  const shape = (s) => (/^[A-Z0-9]{2,}/.test(s) ? 0 : 1);
  const list = [...variants.entries()];
  list.sort(
    (a, b) =>
      Number(b[1].curated) - Number(a[1].curated) ||
      b[1].count - a[1].count ||
      shape(b[0]) - shape(a[0])
  );
  return list[0][0];
};

