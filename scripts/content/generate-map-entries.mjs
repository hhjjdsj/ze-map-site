/* 关卡数复核：dump 的 st 字段偶尔偏低（例：ze_minecraft_universe 记为 1，
   但实体里有 stage1_exit / 31 个 stage2_* 实体，GFL 也登记了 stage2 的 BOSS）。
   这里只在实体名**明确**写了 stageN / lvlN 时才修正，且要求编号基本连续，
   避免把楼层号、偶发命名当成关卡号（例如 [1,10] 这种会被拒绝）。 */
const STAGE_NAME_RE = /(?:^|[^a-z])(?:stage|lvl|level)[\s_-]?(\d{1,2})(?![0-9])/gi;
function stageCountFromEntities(slug, dumpStages) {
  const f = path.join(ROOT, 'public/entity/data', `${slug}.bin`);
  if (!fs.existsSync(f)) return { stages: dumpStages, from: null };
  try {
    const raw = zlib.gunzipSync(fs.readFileSync(f));
    const jlen = raw.readUInt32LE(0);
    const payload = JSON.parse(raw.subarray(4, 4 + jlen).toString('utf8'));
    const nums = new Set();
    let refs = 0;
    for (const e of payload.map.e) {
      if (typeof e[4] !== 'string' || !e[4]) continue;
      let hit = false;
      for (const m of e[4].matchAll(STAGE_NAME_RE)) { nums.add(Number(m[1])); hit = true; }
      if (hit) refs++;
    }
    const maxN = nums.size ? Math.max(...nums) : 0;
    const coverage = maxN ? [...nums].filter((n) => n >= 1 && n <= maxN).length / maxN : 0;
    if (maxN > dumpStages && nums.size >= 2 && refs >= 10 && maxN <= 12 && coverage >= 0.6) {
      return { stages: maxN, from: `实体命名 [${[...nums].sort((a, b) => a - b).join(',')}]` };
    }
  } catch { /* 分片读不了就用原值 */ }
  return { stages: dumpStages, from: null };
}
const excerpt = (s, max = 420) => {
  const t = String(s || '').replace(/\s*\n\s*/g, '\n').trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max);
  const stop = Math.max(cut.lastIndexOf('\n'), cut.lastIndexOf('。'), cut.lastIndexOf('. '));
  return (stop > max * 0.5 ? cut.slice(0, stop) : cut).trim() + ' …';
};

/** MDX 是 JSX 语法：正文里的 < 和 { 会被当成标签/表达式，必须转义 */
const mdSafe = (s) => String(s || '').replace(/</g, '&lt;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;');

/** Markdown 表格单元格：转义竖线（会把列切断）+ JSX 字符，并压掉换行 */
const cell = (s) => mdSafe(String(s ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' '));

/**
 * 「神器 / 道具」表的 Markdown 行。
 * 两个地方要用：一般条目（renderEntry）与手写正文的条目（document 分支）——
 * 后者没法重写正文里的表，只能在正文末尾补一节「社区更正」。
 */
function itemsBlock(rows, { title, lead, showNote }) {
  return [
    `## ${title}`,
    '',
    lead,
    '',
    showNote ? '| 道具 | 冷却 | 使用次数 | 备注 |' : '| 道具 | 冷却 | 使用次数 |',
    showNote ? '|---|---|---|---|' : '|---|---|---|',
    ...rows.map((r) =>
      showNote
        ? `| ${cell(r.name)} | ${cell(cdText(r.cd))} | ${cell(usesText(r.uses))} | ${cell(itemNoteCell(r))} |`
        : `| ${cell(r.name)} | ${cell(cdText(r.cd))} | ${cell(usesText(r.uses))} |`
    ),
    '',
  ];
}

/**
 * 神器 / 道具表的「备注」列。
 * 社区行要能一眼看出「这是玩家改的、原来是多少、谁改的」——
 * 只写新值的话，过两天没人知道这张表和服务器配置哪里不一样了。
 */
function itemNoteCell(row) {
  const who = row.by ? `（${row.by}）` : '';
  const tail = row.note ? `；${row.note}` : '';
  if (row.kind === 'updated') {
    const bits = [];
    if (row.original && row.original.cd !== row.cd) bits.push(`冷却 ${cdText(row.original.cd)} → ${cdText(row.cd)}`);
    if (row.original && row.original.uses !== row.uses) bits.push(`次数 ${usesText(row.original.uses)} → ${usesText(row.uses)}`);
    return `社区更正${bits.length ? `：${bits.join('，')}` : ''}${who}${tail}`;
  }
  if (row.kind === 'added') return `社区补充${who}${tail}`;
  if (row.kind === 'removed') return `社区反馈：本图没有这件道具${who}${tail}`;
  return row.note ?? '';
}

/* ---------------- 人工封面目录索引（文件名大小写不敏感） ----------------
 * 为什么不能按 `<地图英文名>.<ext>` 直接猜路径：
 * Windows / macOS 上截图工具与 GitHub 网页上传经常带出 `.PNG` / `.JPG`（大写），
 * 而线上构建跑在 Linux 上、文件系统区分大小写。只按小写猜路径的后果是
 * 「文件明明在仓库里、页面永远不显示」—— 构建绿、CI 绿、`cover:verify` 也绿
 * （它会把扩展名转小写再判断），又是一次静默失效。2026-09-25 有贡献者报
 * 「传了封面但不生效」，就是这一类。
 *
 * 索引里存的是**磁盘上的真实文件名**，不是拼接出来的名字：
 * cover 会写进 frontmatter 当 URL 用，必须与线上文件名逐字符一致。
 */
const CUSTOM_COVER_DIR = path.join(ROOT, 'public/images/covers/custom');
/** 工坊预览图当封面用的目录（scripts/entity-data/import-workshop-covers.mjs 的产物） */
const WORKSHOP_COVER_DIR = path.join(ROOT, 'public/images/covers/workshop');
/** 取图优先级：同一张图存在多种格式时取列表里靠前的 */
const CUSTOM_COVER_EXTS = ['webp', 'png', 'jpg', 'jpeg'];

/** 建目录索引：`<slug 小写>` → 真实文件名（大小写不敏感，且不依赖 readdir 顺序） */
function buildCoverIndex(dir) {
  const idx = new Map();
  let files = [];
  try { files = fs.readdirSync(dir); } catch { return idx; }
  /* 先排序再建索引：万一存在仅大小写不同的重名文件，取哪个也是确定的，
     不依赖 readdir 的返回顺序（不同系统上顺序不同）。 */
  for (const f of files.slice().sort()) {
    if (f.startsWith('.')) continue;
    const ext = path.extname(f).slice(1).toLowerCase();
    if (!CUSTOM_COVER_EXTS.includes(ext)) continue;
    const key = path.basename(f, path.extname(f)).toLowerCase();
    if (!idx.has(key)) idx.set(key, f);
  }
  return idx;
}

const customCoverIndex = buildCoverIndex(CUSTOM_COVER_DIR);
const workshopCoverIndex = buildCoverIndex(WORKSHOP_COVER_DIR);

const coverIn = (index, dir, mapName) => {
  const slug = String(mapName || '').toLowerCase();
  const f = index.get(slug);
  return f ? `${dir}/${f}` : null;
};

const customCoverOf = (mapName) => coverIn(customCoverIndex, '/images/covers/custom', mapName);
const workshopCoverOf = (mapName) => coverIn(workshopCoverIndex, '/images/covers/workshop', mapName);

/**
 * 一张图最终用哪张封面：人工 > 工坊预览图 > 渲染兜底。
 * 兜底图是本站在实体数据上算出来的俯视密度点图（黑底彩点），当 hero 底图几乎等于没有 ——
 * 所以三层必须**都走这一个函数**，不然就会漏（2026-10-08：手写正文的三张图漏了，
 * 魔晄炉明明已经有作者预览图，页面上却一直挂着那张黑底点图）。
 *
 * `pageSlug` 是页面文件名，跟实体名不一定一样：魔晄炉的页面是 ze_ffvii_mako_reactor，
 * 实体却叫 ze_ffvii_mako_reactor_v6_p —— 人工/工坊图按**页面名**命名（人挑图时看的是页面），
 * 所以两个名字都要试；层级顺序不因此改变（先两个名字里找人工，再两个名字里找工坊）。
 */
const resolveCover = (rec, pageSlug = rec.m) => {
  const names = pageSlug === rec.m ? [rec.m] : [pageSlug, rec.m];
  const rel =
    names.map((nm) => customCoverOf(nm)).find(Boolean) ??
    names.map((nm) => workshopCoverOf(nm)).find(Boolean) ??
    `/images/covers/${rec.s}.webp`;
  return fs.existsSync(path.join(ROOT, 'public', rel)) ? rel : null;
};

/**
 * 手写正文条目的封面：**只动 frontmatter 里的 cover 行**，正文一个字不碰。
 * 没有 cover 行就补在 frontmatter 末尾；frontmatter 结构不认识就原样返回，绝不瞎猜。
 */
const withResolvedCover = (text, coverRel) => {
  if (!coverRel || !text.startsWith('---\n')) return text;
  const end = text.indexOf('\n---', 3);
  if (end < 0) return text;
  const head = text.slice(0, end + 1);
  const rest = text.slice(end + 1);
  const line = `cover: ${JSON.stringify(coverRel)}`;
  const next = /^cover:.*$/m.test(head) ? head.replace(/^cover:.*$/m, line) : `${head}${line}\n`;
  return next + rest;
};

/* ---------------- 图片集在正文里的位置 ----------------

   站长要求（2026-10-08）：图片集**排在正文靠上** —— 紧跟「背景故事」小节，
   正文里没有这一节的就紧跟正文开头；总之别压在最后那堆自动生成的资料段后面。

   实现方式：正文里放一行 `<MapGallery slug="…" cover="…" />` 标记，详情页用
   `<Content components={{ MapGallery }} />` 让 MDX 认得它（见 components/MapGallery.astro）。
   标记由生成器负责：数据条目的正文每轮都重写，位置天然固定；
   手写正文的条目（魔晄炉 / 米纳斯 / 黑珍珠号）正文照抄不动，但**这一行由 ensureGalleryMarker 维护** ——
   找不到就补、位置不对就搬、slug/cover 变了就更新。所以：
     · 贡献者提 PR 只改正文，标记不会丢（下一轮构建会补回来）；
     · 社区投稿写回仓库后重新生成，标记照旧落在正确位置。
*/

/** 正文里的图片集标记（属性顺序固定，方便 diff 稳定） */
const galleryMarker = (slug, coverRel) =>
  `<MapGallery slug=${JSON.stringify(slug)}${coverRel ? ` cover=${JSON.stringify(coverRel)}` : ''} />`;

/** frontmatter 与正文的分界（返回正文起始下标） */
const bodyStartOf = (text) => {
  if (!text.startsWith('---\n')) return 0;
  const end = text.indexOf('\n---', 3);
  return end < 0 ? 0 : end + 1;
};

/**
 * 手写正文条目：保证标记存在且位置正确。
 * 位置：`## 背景故事` 那一节之后 → 没有就正文第一个 `##` 小节之后 → 再没有就放正文末尾。
 * 返回 { text, where, moved }：where 是落点说明（日志里打出来），moved 表示这次动过。
 */
const ensureGalleryMarker = (text, slug, coverRel) => {
  const marker = galleryMarker(slug, coverRel);
  const start = bodyStartOf(text);
  const fm = text.slice(0, start);
  /* 先把已有的标记行摘掉（可能在别处、可能是旧的 slug/cover），下面统一重新插 */
  const had = /^<MapGallery\b[^\n]*\/>\s*$/m.test(text);
  let body = text
    .slice(start)
    .replace(/^[ \t]*<MapGallery\b[^\n]*\/>[ \t]*\r?\n?/gm, '')
    .replace(/\n{3,}/g, '\n\n');

  const lines = body.split('\n');
  const h2 = [];
  lines.forEach((l, i) => {
    if (/^##\s+\S/.test(l)) h2.push(i);
  });

  const storyAt = h2.find((i) => /^##\s*背景故事/.test(lines[i]));
  let at;
  let where;
  if (storyAt !== undefined) {
    const next = h2.find((i) => i > storyAt);
    at = next === undefined ? lines.length : next;
    where = '背景故事小节之后';
  } else if (h2.length) {
    const next = h2.find((i) => i > h2[0]);
    at = next === undefined ? lines.length : next;
    where = '正文第一个小节之后';
  } else {
    at = lines.length;
    where = '正文末尾';
  }
  /* 插到 at 之前，并保证标记前后各有一个空行 ——
     MDX 里紧贴段落的 JSX 会被当成**行内**元素解析，`<section>` 就塞进 `<p>` 里了（结构坏掉） */
  while (at > 0 && lines[at - 1].trim() === '') at--;
  lines.splice(at, 0, ...(at > 0 ? ['', marker, ''] : [marker, '']));
  body = lines.join('\n').replace(/\n{3,}/g, '\n\n');
  if (!body.endsWith('\n')) body += '\n';
  return { text: fm + body, where, moved: !had || text !== fm + body };
};

/* ---------------- 生成一个条目的 MDX ---------------- */
function renderEntry(rec, research, wsRec, gfl) {
  const slug = rec.m;
  const wsUrl = `https://steamcommunity.com/sharedfiles/filedetails/?id=${rec.f}`;
  const groups = Object.fromEntries((catalog.groups || []).map((g) => [g.id, g]));
  const baked = rec.source === BAKED_SOURCE;
  const provenance = baked
    ? 'Steam 创意工坊地图包中的实体定义（Source2Viewer 解析）'
    : `${normalizeEntitySource(rec.source || catalog.meta.legacySource)}（${rec.sourceBuilt || catalog.meta.legacyBuilt}）`;
  const cats = Object.entries(rec.c || {}).sort((a, b) => b[1] - a[1]);
  const subs = wsRec?.result === 1 ? (wsRec.subscriptions ?? 0) : 0;
  const tags = [
    ...new Set(
      [
        ...autoTags(rec),
        ...(subs >= 5000 ? ['热门'] : []),
        ...(wsRec && wsRec.result !== 1 ? ['已下架'] : []),
        ...(research?.tags || []),
      ]
        .map(safeTag)
        .map(canonTag)
        .filter(Boolean)
    ),
  ];
  // 难度：先用共享表把旧称归一（中等→普通 等），再严格校验当前枚举，认不出来退回「未知」。
  // 用 DIFFICULTIES 而不是本地硬编码数组，改名时不会再漏掉这一处。
  const researchDiff = normalizeDifficulty(research?.difficulty);
  const diff = isDifficulty(researchDiff) ? researchDiff : '未知';
  // 发布日期优先用工坊 API 的权威时间
  const released = wsRec?.timeCreated || rec.d;
  const updated = wsRec?.timeUpdated || rec.d || (baked ? null : catalog.meta.legacyBuilt.slice(0, 10));
  const desc = wsRec?.result === 1 ? (wsRec.description || '').trim() : '';
  const hasEditorial = Boolean(research?.summary);
  /*
   * 封面优先级：
   *   1. 人工上传的 public/images/covers/custom/<地图内部名>.<ext>
   *      （自己用 `npm run cover:set` 生成，或者贡献者直接往这个目录传图）
   *   2. 作者上传的工坊预览图 public/images/covers/workshop/<地图内部名>.<ext>
   *      （`npm run cover:workshop` 从 bake/gallery 导进来的，2026-10-07 起）
   *   3. 实体数据渲染的 /images/covers/<分片名>.webp（render-covers.mjs 的产物）
   * 人工封面特意放在 custom/ 子目录：渲染目录（render-covers.mjs）默认会跳过已存在的文件，
   * 直接换掉渲染图平时也能用，但 `--force` 重渲染会冲掉它，事后也分不清哪张是人换的。
   * 放 custom/ 两者互不干扰，删掉那里的文件即可换回渲染图。
   *
   * 第 2 层为什么存在：渲染图是本站算出来的密度雷达示意图，跟「地图长什么样」差得远；
   * 工坊预览图是作者自己的真实截图（555×312，正好 16:9），
   * 详情页 hero 只把它当 22% 透明度的氛围底图，卡片按 16:9 裁切，这个尺寸够用。
   * 它**复制进仓库**而不是直接引 R2：terr.ze-map.cn 在国内部分网络下不通，
   * 而封面是每个卡片都要加载的东西，必须跟其它封面一样走本站同源。
   *
   * 为什么认多种扩展名而不是只认 webp：贡献者大多不会转 webp（要装工具），
   * 但人人都会从截图工具里存出 png / jpg。只认 webp 等于把「提 PR 换封面」这条路堵死。
   * 查找走 customCoverOf() / workshopCoverOf()：**大小写不敏感**，
   * 且返回磁盘上的真实文件名（见上方索引注释）。
   */
  const coverRel = resolveCover(rec);
  const hasCover = Boolean(coverRel);
  // 上传者昵称：仅在正文说明里用，不冒充「作者」（很多是 CS2 移植上传者）
  const uploader = wsRec?.result === 1 ? uploaderOf(wsRec.creator) : '';
  // 作者署名可能很长（多作者 / 原作与移植的区分）：侧栏只显示第一段，完整署名放 authorNote
  const rawAuthor = (research?.author || '').trim();
  const authorShort = rawAuthor.includes('；') ? rawAuthor.split('；')[0].trim() : rawAuthor;
  const authorNote = rawAuthor && authorShort !== rawAuthor ? rawAuthor : '';

  const fm = [
    '---',
    `title: ${JSON.stringify((research?.title || rec.cn || rec.m).trim())}`,
    `titleEn: ${JSON.stringify(rec.m)}`,
    `game: CS2`,
    research?.author ? `author: ${JSON.stringify(authorShort)}` : null,
    authorNote ? `authorNote: ${JSON.stringify(authorNote)}` : null,
    `difficulty: ${diff}`,
    research?.players ? `players: ${JSON.stringify(research.players)}` : null,
    research?.duration ? `duration: ${JSON.stringify(research.duration)}` : null,
    `stages: ${rec.st || 0}`,
    `tags: [${tags.map((x) => JSON.stringify(x)).join(', ')}]`,
    hasCover ? `cover: ${JSON.stringify(coverRel)}` : null,
    `workshopUrl: ${wsUrl}`,
    `workshopId: ${JSON.stringify(rec.f)}`,
    subs ? `workshopSubs: ${subs}` : null,
    wsRec?.views ? `workshopViews: ${wsRec.views}` : null,
    uploader && !research?.author ? `uploader: ${JSON.stringify(uploader)}` : null,
    wsRec && wsRec.result !== 1 ? `workshopMissing: true` : null,
    `entitySlug: ${JSON.stringify(rec.s)}`,
    `entityKey: ${JSON.stringify(rec.k)}`,
    `entityCount: ${rec.n}`,
    released ? `releaseDate: ${JSON.stringify(released)}` : null,
    updated ? `lastUpdated: ${JSON.stringify(updated)}` : null,
    research?.videoUrls?.length ? `videoUrls: [${research.videoUrls.map((x) => JSON.stringify(x)).join(', ')}]` : null,
    research?.sources?.length ? `sources: [${research.sources.map((x) => JSON.stringify(x)).join(', ')}]` : null,
    `stub: ${hasEditorial ? 'false' : 'true'}`,
    '---',
    '',
    `{/* ${MARK} · 实体数据：${provenance} · 工坊数据：Steam Web API */}`,
    '',
  ].filter(Boolean);

  /*
   * 正文分三段拼装（2026-09-30 信息层级重排）：
   *   intro    人工资料的开头（摘要/背景故事）—— 读者第一眼看到的就是它
   *   gameplay 玩家真正关心的：关卡 → 神器 / 道具 → BOSS → 音乐
   *   meta     资料性内容：工坊自述 → 数据概况 → 实体构成 → 实体预览 → 来源 → 说明
   * 以前是一股脑按「工坊自述 → 数据概况 → 实体构成 → 关卡 → 神器…」推，
   * 结果玩家要翻过三节后台性质的内容才看到神器表（2026-09-30 反馈：页杂而不精）。
   * 只调整**段落顺序**，每一段的内容与来源说明一个字都没改 —— 改资料仍然只改 data/research/*.json。
   */
  const intro = [];
  const gameplay = [];
  const meta = [];

  if (hasEditorial) {
    intro.push(mdSafe(research.summary.trim()), '');
  }
  // 数据条目的「资料待补充」提示由详情页统一渲染（stub 字段），正文里不再重复

  if (desc) {
    meta.push(
      '## 工坊页面自述',
      '',
      '> ' + mdSafe(excerpt(desc)).split('\n').filter(Boolean).join('\n> '),
      '',
      `> 以上为作者在工坊页面的原文摘录，完整内容见 [Steam 创意工坊](${wsUrl})。`,
      ''
    );
  } else if (wsRec && wsRec.result !== 1) {
    meta.push(
      '> 该地图的工坊条目在 Steam 上已**查无此项**（可能是作者删除或设为隐藏），下方实体数据仍保留在本站分片中。',
      ''
    );
  }

  meta.push(
    '## 数据概况',
    '',
    '| 项目 | 内容 |',
    '|---|---|',
    `| 地图英文名 | ${rec.m} |`,
    `| 工坊文件 ID | [${rec.f}](${wsUrl}) |`,
    uploader ? `| 工坊上传者 | ${uploader} |` : null,
    `| 适用游戏 | CS2 |`,
    released ? `| 工坊发布 | ${released} |` : null,
    wsRec?.timeUpdated ? `| 工坊最近更新 | ${wsRec.timeUpdated} |` : null,
    subs ? `| 工坊订阅数 | ${n(subs)} |` : null,
    wsRec?.views ? `| 工坊浏览量 | ${n(wsRec.views)} |` : null,
    `| 实体总数 | ${n(rec.n)} |`,
    `| 分片点位 | ${n(rec.k2)} |`,
    `| 关卡数 | ${rec.st || 0}${rec.st ? '（按实体命名推断）' : ''} |`,
    ''
  );

  meta.push(
    '## 实体构成',
    '',
    `本图共记录 ${n(rec.n)} 个实体，分片包含 ${n(rec.k2)} 个实体点位：`,
    '',
    '| 类别 | 数量 |',
    '|---|---|',
    ...cats.map(([gid, cnt]) => `| ${groups[gid]?.label || gid} | ${n(cnt)} |`),
    '',
    (rec.t || []).length
      ? `数量最多的实体类型：${rec.t.slice(0, 6).map((x) => `\`${x[0]}\` ${n(x[1])}`).join(' · ')}。`
      : null,
    ''
  );

  if (rec.st) {
    gameplay.push(
      '## 关卡',
      '',
      `按实体命名（\`lvl2\` / \`stage3\` 之类）推断，本图共 **${rec.st}** 个关卡。`,
      '在实体预览里可以按关卡分层查看，切换关卡时镜头会自动飞到该关范围。',
      ''
    );
  }

  /* 神器 / 道具：服务器配置打底，社区投稿逐行盖上（原值留在备注里）。
     生成器**读社区文档**是有意的：表格在正文里，读时合并得让 MDX 里带组件，
     而 MDX 一律由脚本生成 —— 两边都真实、且输出仍然确定（社区文件是入库的）。 */
  const communityRows = communityItemsOf(rec.m);
  const merged = mergeItems(gfl?.items ?? [], communityRows);
  const communityCount = merged.rows.filter((r) => r.kind !== 'server').length;

  if (merged.rows.length) {
    /* 备注列只在真的有社区行时出现：没有社区投稿的图，表格保持三列，
       免得 340 多个条目凭空多出一列空白（也免得 diff 里全是噪音）。 */
    const showNote = communityCount > 0;
    const title = gfl?.items?.length ? '神器 / 道具（服务器配置）' : '神器 / 道具（社区补充）';
    const lead = gfl?.items?.length
      ? `以下 ${merged.rows.length} 件道具来自公开的服务器 entwatch 配置，是本图在服务器上实际注册的神器与道具${
          gfl._from ? `（取自 GFL 的 \`${gfl._from}\` 配置）` : ''
        }${communityCount ? '；备注里标了「社区更正 / 社区补充」的行来自社区投稿' : ''}：`
      : `本站没有这张图的服务器配置解析结果，以下 ${merged.rows.length} 件来自[社区投稿](/contribute/)补充：`;
    gameplay.push(...itemsBlock(merged.rows, { title, lead, showNote }));
  }

  if (gfl?.bosses?.length) {
    gameplay.push(
      '## BOSS',
      '',
      `服务器 bosshud 配置登记了 ${gfl.bosses.length} 个 BOSS：${gfl.bosses.map((b) => mdSafe(b)).join(' · ')}。`,
      ''
    );
  }

  if (gfl?.music?.length) {
    const shown = gfl.music.slice(0, 12);
    gameplay.push(
      '## 音乐',
      '',
      `本图在服务器上登记了 ${gfl.music.length} 首 BGM，例如：`,
      '',
      ...shown.map((t) => `- ${mdSafe(t)}`),
      gfl.music.length > shown.length ? `- …等共 ${gfl.music.length} 首` : null,
      ''
    );
  }

  meta.push(
    '## 实体预览',
    '',
    `[打开《${rec.cn || rec.m}》的实体预览 →](/preview/?map=${rec.s})`,
    '',
    '可交互查看本图的可破坏物、传送门、机关、危险区、路径点等点位，支持 3D / 平面两种视图与关卡分层。',
    ''
  );

  if (research?.sources?.length) {
    meta.push('## 资料来源', '', ...research.sources.map((s) => `- ${s}`), '');
  }

  meta.push(
    '## 数据说明',
    '',
    `- 实体数据来源：${provenance}。`,
    baked ? '- 实体点位来自地图实体定义；有模型碰撞壳的刷子实体带真实包围盒，其余使用类别典型尺寸。' : '- 历史快照的实体点位和体积说明保留原始口径。',
    gfl ? '- 神器 / 道具、BOSS 与音乐名单来自 GFL 公开服务器配置（entwatch / bosshud / musicname），可能与其它服务器不一致。' : null,
    communityCount
      ? '- 神器 / 道具表里标注「社区更正 / 社区补充」的行来自社区投稿（投稿页提交、人工审核）；原值保留在备注里，未标注的行仍是服务器配置原值。'
      : null,
    '- 关卡数由实体命名（lvl2 / stage3 等）推断，未命名的按就近标注推断，可能与服务器配置或实际流程略有出入。',
    ''
  );

  const body = [...intro, galleryMarker(rec.m, coverRel), '', ...gameplay, ...meta];
  /*
   * 标记前后各留一个空行：MDX 里紧贴段落的 JSX 会被当成**行内**元素解析，
   * `<section>` 会被塞进 `<p>` 里 —— HTML 结构坏掉，浏览器自己"修"出来的树会很怪。
   * ⚠️ 要在**拼接之后**再规范：标记前面那一行往往是 frontmatter 数组里的 MDX 注释，
   * 只对 body 做替换是碰不到它的（2026-10-08 踩过）。
   */
  return (fm.join('\n') + '\n' + body.filter((x) => x !== null).join('\n'))
    .replace(/([^\n])\n(<MapGallery\b[^\n]*\/>)/, '$1\n\n$2')
    .replace(/(<MapGallery\b[^\n]*\/>)\n(?=[^\n])/, '$1\n\n');
}

